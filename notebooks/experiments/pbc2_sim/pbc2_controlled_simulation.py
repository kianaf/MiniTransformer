"""§3.1.2 controlled simulation on top of the real binarised PBC2 cohort.

Design (after deciding to keep predictors binary):
- Predictors: real binarised PBC2 values, loaded via load_real_data("pbc2").
  9 binary predictors per visit. Untouched.
- Target: the existing `ascites` column (last in the CSV) is OVERWRITTEN
  with a synthetic binary y_t generated by the same j1 -> j2 -> j3 rule as
  the synthetic simulation, with:
      j1 = bili_high     (real binary column, index 8)
      j2 = albumin_low   (real binary column, index 3)
      j3 = ascites       (the target column we overwrite, index 9)
  y_t = 1 w.p. 0.9 when (seenfirst AND seensecond) at the start of step t,
  else 0. When y_t = 1 the trigger flags reset, matching the synthetic
  simulation's reset-on-fire dynamics.

The other seven binarised markers (hepato, spiders, edema, alkphos_high,
ast_high, platelet_low, protime_high) are NOT direct inputs to the rule
but they share real PBC2 correlations with the triggers through the
clinical disease progression. The §2.3 test should rank j1 and j2 above
the other seven, even though those carry indirect signal through real
disease biology. This is the controlled "real-substrate + synthetic
target" simulation the response letter §3.1.2 describes.

Outputs (under notebooks/results/pbc2_controlled_simulation/):
    mse.csv            per-target MSE table (10-fold CV)
    test.csv           per-variable mean p-value + rank
    marginal.txt       synthetic target's positive rate
    summary.txt        human-readable summary
"""
import os
import sys
import time

_THIS_DIR = os.path.dirname(os.path.abspath(__file__))
_PROJECT_ROOT = os.path.abspath(os.path.join(_THIS_DIR, "..", "..", ".."))
os.chdir(_PROJECT_ROOT)
if _PROJECT_ROOT not in sys.path:
    sys.path.insert(0, _PROJECT_ROOT)

import numpy as np
import pandas as pd
import torch
import torch.optim as optim
from torch.utils.data import DataLoader
from sklearn.model_selection import KFold

from src.data_preparation import load_real_data, collate_function
from src.transformers import (
    MiniTransformer,
    create_custom_mask_pair,
    create_distance_to_end_matrix,
    create_pairwise_distance_matrix,
    train_mini_transformer,
)
from src.statistical_testing import statistical_testing
from src.pbc2_substrate import (
    inject_synthetic_target,
    COL_BILI_HIGH,
    COL_ALBUMIN_LOW,
    COL_ASCITES,
    P_SUCCESS,
)


device = torch.device("cpu")

SEEDS = [0, 1, 11, 42, 123, 999, 1337, 2025, 9999, 12345]

# MiniTransformer hyperparameters (paper §3.2 real-data defaults)
NHEADS = 8
NCUM = 8
DK = 1
DV = 1
MAXLEN = 10

BATCH_SIZE = 1
LR = 1e-3
LAMBDA_L2 = 1e-3
EPOCHS = int(os.environ.get("PBC2_SIM_EPOCHS", 150))

# §2.3 test config
TEST_NREPP = int(os.environ.get("PBC2_SIM_NREPP", 500))
TEST_V = int(os.environ.get("PBC2_SIM_V", 7))
TEST_SEED = 123456789

# Cross-validation
N_SPLITS = 10
CV_RANDOM_STATE = 42

# Synthetic-target rule constants (P_SUCCESS, COL_BILI_HIGH, COL_ALBUMIN_LOW,
# COL_ASCITES) and inject_synthetic_target() live in src/pbc2_substrate.py so
# the pbc2-sim driver scripts share one source of truth.
VAR_NAMES = [
    "hepatomegaly", "spiders", "edema_present", "albumin_low",
    "alkphos_high", "ast_high", "platelet_low", "protime_high",
    "bili_high", "y_synthetic",
]

OUT_DIR = "notebooks/results/pbc2_controlled_simulation"
os.makedirs(OUT_DIR, exist_ok=True)


# --------------------------------------------------------------------------- #
# Training / eval / test helpers                                              #
# --------------------------------------------------------------------------- #

def per_target_mse_torch_model(model, test_data):
    model.eval()
    p_local = test_data[0].shape[1]
    se, n_eval = np.zeros(p_local), 0
    with torch.no_grad():
        for seq in test_data:
            if seq.shape[0] < 3:
                continue
            x = seq.unsqueeze(0)
            mask = torch.ones_like(x, dtype=torch.bool)
            pred = model((x[:, :-1, :], mask[:, :-1, :]))
            se += (pred[0, -1].numpy() - seq[-1].numpy()) ** 2
            n_eval += 1
    return se / max(n_eval, 1)


def train_and_eval(model, train_data, test_data):
    loader = DataLoader(train_data, batch_size=BATCH_SIZE, shuffle=True,
                        collate_fn=collate_function, num_workers=0)
    opt = optim.Adam(model.parameters(), lr=LR)
    train_mini_transformer(model, loader, None, opt, LAMBDA_L2, EPOCHS, device)
    return per_target_mse_torch_model(model, test_data)


# --------------------------------------------------------------------------- #
# Main                                                                        #
# --------------------------------------------------------------------------- #

def main():
    torch.set_printoptions(sci_mode=False, precision=6)
    t0 = time.time()
    print("=== PBC2 controlled simulation (binarised predictors, synthetic target) ===")
    raw_tensors, max_T = load_real_data("pbc2")
    n_total = len(raw_tensors)
    p = raw_tensors[0].shape[1]
    print(f"Cohort: n={n_total} patients, p={p}, max_T={max_T}")
    print(f"Triggers: j1=bili_high (col {COL_BILI_HIGH}), "
          f"j2=albumin_low (col {COL_ALBUMIN_LOW})")
    print(f"Target overwritten: ascites (col {COL_ASCITES})")
    print(f"Seeds: {SEEDS}")
    print(f"Config: EPOCHS={EPOCHS}, V={TEST_V}, nrepp={TEST_NREPP}")
    assert p == 10
    assert COL_ASCITES == p - 1

    # Inject synthetic target ONCE (deterministic with fixed seed). CV
    # randomness is over patient splits, not target generation.
    seqs, z_list, y_list = inject_synthetic_target(raw_tensors, seed=42)

    flat_y = np.concatenate(y_list)
    flat_z = np.concatenate(z_list)
    marg_msg = (f"synthetic target marginal: P(y=1) = {flat_y.mean():.3f}  "
                f"(P(z=1) = {flat_z.mean():.3f})")
    print(f"  {marg_msg}")
    with open(os.path.join(OUT_DIR, "marginal.txt"), "w") as f:
        f.write(marg_msg + "\n")
        f.write(f"n_visits total: {len(flat_y)}\n")
        f.write(f"n_patients: {n_total}\n")

    mask_pairwise = create_custom_mask_pair(MAXLEN, device)
    distance_to_end_matrix = create_distance_to_end_matrix(MAXLEN, device)
    pairwise_distance_matrix = create_pairwise_distance_matrix(MAXLEN, device)

    folds = list(KFold(n_splits=N_SPLITS, shuffle=True,
                        random_state=CV_RANDOM_STATE).split(np.arange(n_total)))
    assert len(folds) == len(SEEDS)

    mse_per_fold = []
    pvals_per_fold = []

    for f_idx, ((tr_idx, te_idx), seed) in enumerate(zip(folds, SEEDS)):
        train_ds = [seqs[i] for i in tr_idx]
        test_ds = [seqs[i] for i in te_idx]
        print(f"--- fold {f_idx+1}/{N_SPLITS}, seed={seed} "
              f"(n_train={len(train_ds)}, n_test={len(test_ds)}) ---")

        torch.manual_seed(seed); np.random.seed(seed)
        model = MiniTransformer(p, NHEADS, DK, DV, NCUM,
                                mask_pairwise, pairwise_distance_matrix,
                                distance_to_end_matrix, device).to(device)
        per_var_mse = train_and_eval(model, train_ds, test_ds)
        mse_per_fold.append(per_var_mse)
        print(f"  MSE_target = {per_var_mse[COL_ASCITES]:.4f}  "
              f"MSE_mean = {per_var_mse.mean():.4f}")

        avepval, _, _, _ = statistical_testing(
            model, train_ds, p=p, predindex=COL_ASCITES,
            nrepp=TEST_NREPP, target_sample_size=TEST_V,
            return_pval_mat=False, seed=TEST_SEED,
        )
        pvals_per_fold.append(avepval)
        bili_p = float(avepval[COL_BILI_HIGH])
        alb_p = float(avepval[COL_ALBUMIN_LOW])
        non_trigger = [j for j in range(p)
                       if j not in (COL_BILI_HIGH, COL_ALBUMIN_LOW, COL_ASCITES)]
        min_nontrig = min(float(avepval[j]) for j in non_trigger)
        print(f"  §2.3: bili_high p={bili_p:.3f}  albumin_low p={alb_p:.3f}  "
              f"min non-trigger p={min_nontrig:.3f}")

    print(f"\nAll folds done in {time.time() - t0:.1f}s")

    # ----------------------- aggregate ------------------------------------- #
    mse_arr = np.stack(mse_per_fold)
    pv_arr = np.stack(pvals_per_fold)

    mse_rows = []
    for j in range(p):
        mse_rows.append({
            "var": j, "name": VAR_NAMES[j],
            "mse_mean": float(mse_arr[:, j].mean()),
            "mse_std": float(mse_arr[:, j].std()),
            "is_target": j == COL_ASCITES,
        })
    pd.DataFrame(mse_rows).to_csv(
        os.path.join(OUT_DIR, "mse.csv"), index=False, float_format="%.5f")

    mean_p = pv_arr.mean(axis=0)
    std_p = pv_arr.std(axis=0)
    test_rows = []
    for j in range(p):
        if j == COL_ASCITES:
            continue
        test_rows.append({
            "var": j, "name": VAR_NAMES[j],
            "mean_p": float(mean_p[j]),
            "std_p": float(std_p[j]),
            "is_trigger": j in (COL_BILI_HIGH, COL_ALBUMIN_LOW),
        })
    test_df = pd.DataFrame(test_rows).sort_values("mean_p").reset_index(drop=True)
    test_df["rank"] = test_df.index + 1
    test_df.to_csv(os.path.join(OUT_DIR, "test.csv"),
                    index=False, float_format="%.5f")

    # ----------------------- text summary ---------------------------------- #
    lines = []
    lines.append("=== PBC2 controlled simulation (response §3.1.2) ===")
    lines.append(f"Cohort: real binarised PBC2, {n_total} patients. "
                 f"Predictors untouched, ascites column overwritten.")
    lines.append(f"Triggers: j1 = bili_high, j2 = albumin_low.")
    lines.append(f"Target: binary synthetic y_t (column {COL_ASCITES}).")
    lines.append(f"Protocol: 10-fold CV, EPOCHS={EPOCHS}, V={TEST_V}, "
                 f"nrepp={TEST_NREPP}.")
    lines.append(f"  {marg_msg}")
    lines.append("")
    lines.append(f"MSE_target = {mse_arr[:, COL_ASCITES].mean():.4f} "
                 f"± {mse_arr[:, COL_ASCITES].std():.4f}")
    lines.append("")
    lines.append("§2.3 ranking by mean p-value (target excluded):")
    for _, row in test_df.iterrows():
        tag = "  <-- TRIGGER" if row["is_trigger"] else ""
        lines.append(f"  #{row['rank']:>2}  {row['name']:<15s}  "
                     f"mean_p={row['mean_p']:.3f}  std_p={row['std_p']:.3f}{tag}")
    triggers_at_top = (test_df.iloc[:2]["is_trigger"].sum() == 2)
    lines.append(f"\ntriggers in top-2 by mean_p: "
                 f"{'YES' if triggers_at_top else 'NO'}")

    summary_txt = "\n".join(lines)
    print("\n" + summary_txt)
    with open(os.path.join(OUT_DIR, "summary.txt"), "w") as f:
        f.write(summary_txt + "\n")
    print(f"\nResults written to {OUT_DIR}/")


if __name__ == "__main__":
    main()
